bool oled_task_user(void) {
    if (last_input_activity_elapsed() > 60000) {
        oled_off();
        return false;
    } else {
        oled_on();
    }
    
    // Switch frames smoothly based on your input activity clock
    if (last_input_activity_elapsed() < 250) {
        oled_write_raw_P(bongo_tap, sizeof(bongo_tap));
    } else {
        oled_write_raw_P(bongo_rest, sizeof(bongo_rest));
    }
    return false;
}
