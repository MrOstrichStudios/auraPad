// Smooth reactive lighting engine handlers
uint16_t white_flash_timer = 0;
uint8_t current_brightness = 0;

void keyboard_post_init_user(void) {
    rgblight_enable_noeeprom();
    rgblight_mode_noeeprom(RGBLIGHT_MODE_STATIC_LIGHT);
    rgblight_sethsv_noeeprom(0, 0, 0);
}

bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    if (record->event.pressed) {
        current_brightness = 255;
        rgblight_sethsv_noeeprom(0, 0, current_brightness);
        white_flash_timer = timer_read();
    }
    return true;
}

void matrix_scan_user(void) {
    if (current_brightness > 0) {
        if (timer_elapsed(white_flash_timer) > 3) {
            current_brightness = (current_brightness > 5) ? (current_brightness - 5) : 0;
            rgblight_sethsv_noeeprom(0, 0, current_brightness);
            white_flash_timer = timer_read();
        }
    }
}